function fold(s) {
  return String(s || '').toLowerCase().normalize('NFC')
    .replace(/[็-๎]/g, '')              // วรรณยุกต์ ไม้ไต่คู้ ทัณฑฆาต
    .replace(/[^฀-๿a-z0-9]/g, '')       // เหลือเฉพาะตัวอักษร
    .replace(/(.)\1{2,}/g, '$1')                  // ราคาาาา -> ราคา
    .split('').map((c) => SAME[c] || c).join('');
}

function distance(a, b) {
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
    prev = cur;
  }
  return prev[b.length];
}

function similar(q, k) {
  if (!q || !k) return 0;
  if (q === k) return 1;
  const long = q.length >= k.length ? q : k;
  const short = q.length >= k.length ? k : q;
  if (short.length >= 2 && long.includes(short)) return 0.95;   // คีย์เวิร์ดอยู่ในประโยค
  return 1 - distance(q, k) / long.length;
}

